import { ApolloClient, ApolloLink, HttpLink, InMemoryCache } from '@apollo/client';
import { buildClientSchema } from 'graphql';

import * as introspectionResult from './__autogenerated__/schema.json';
import { useMemo } from 'react';

// will eventually need this for scalar support
const schema = buildClientSchema(introspectionResult as any);

export const useClient = (uri: string) => useMemo(() => new ApolloClient({
  cache: new InMemoryCache({
    typePolicies: {
      Query: {
        fields: {
          entries: {
            merge: (_, incoming) => incoming,
          },
          incompleteEntries: {
            merge: (_, incoming) => incoming,
          },
        }
      }
    }
  }),
  link: new HttpLink({ uri })
}), [uri])