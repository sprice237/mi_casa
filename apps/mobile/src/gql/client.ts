import { scalars } from '@mi_casa/gql';
import { ApolloClient, ApolloLink, HttpLink, InMemoryCache } from '@apollo/client';
import { SetContextLink } from '@apollo/client/link/context';
import { buildClientSchema } from 'graphql';

import * as introspectionResult from './__autogenerated__/schema.json';
import { useMemo } from 'react';
import { withScalars } from '$/apollo-link-scalars';
import { useEndpointsStore } from '$/stores/endpointsStore';
import { useAuthStore } from '$/stores/authStore';

const schema = buildClientSchema(introspectionResult as any);

export const useClient = () => {
  const uri = useEndpointsStore(state => state.apiUri);

  return useMemo(() => new ApolloClient({
    cache: new InMemoryCache({
      typePolicies: {
        Query: {
          fields: {
            entries: {
              merge: (_, incoming) => incoming,
            },
            incompleteEntries: {
              merge: (_, incoming) => incoming,
            },
          }
        }
      }
    }),
    link: ApolloLink.from([
      withScalars({
        schema, typesMap: scalars
      }),

      // TODO -- use ErrorLink or RetryLink

      new SetContextLink(async ({ headers }) => {
        const { auth } = useAuthStore.getState();

        if (!auth) {
          throw new Error('missing auth')
        }

        return {
          headers: {
            ...headers,
            authorization: `Bearer ${auth.token}`
          }
        }
      }),
      new HttpLink({ uri })
    ])
  }), [uri])
}